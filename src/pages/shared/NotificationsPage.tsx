import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { BellIcon, CheckCheckIcon } from 'lucide-react';
import { Button } from '../../components/ui/Button';
import { EmptyState, PageHeader, Panel, Segmented } from '../../components/ui/Primitives';
import { useAuth } from '../../contexts/AuthContext';
import { useData } from '../../contexts/DataContext';
import type { AppNotification, Tone } from '@shared/types';
import { cn } from '../../utils/cn';
import { cmd } from '../../utils/commands';
import { fmtDateTime } from '@shared/domain/time';

const dot: Record<Tone, string> = { ok: 'bg-ok', warn: 'bg-warn', bad: 'bg-bad', info: 'bg-info', brand: 'bg-brand-600', neutral: 'bg-ink-faint' };

export function NotificationsPage() {
  const { user } = useAuth();
  const { state, run } = useData();
  const navigate = useNavigate();
  const [filter, setFilter] = useState<'all' | 'unread'>('all');
  const audience = user?.role === 'management' ? 'management' : user?.employeeId ?? '';
  const mine = state.notifications.filter((n) => n.audience === audience);
  const shown = filter === 'unread' ? mine.filter((n) => !n.read) : mine;
  const unread = mine.filter((n) => !n.read).length;

  const markRead = (ids: string[]) => run(cmd.markNotificationsRead(ids));
  const open = (n: AppNotification) => {
    if (!n.read) markRead([n.id]);
    navigate(n.link);
  };

  return (
    <div>
      <PageHeader title="Notifications" description="Notifications are generated by the system and stored with your records."
      actions={<Button variant="secondary" icon={CheckCheckIcon} disabled={!unread} onClick={() => markRead(mine.map((n) => n.id))}>Mark all as read</Button>} />
      <div className="mb-4">
        <Segmented label="Filter" value={filter} onChange={setFilter} options={[{ value: 'all', label: `All (${mine.length})` }, { value: 'unread', label: `Unread (${unread})` }]} />
      </div>
      <Panel flush>
        {shown.length === 0 ? <EmptyState icon={BellIcon} title={filter === 'unread' ? 'No unread notifications' : 'No notifications yet'} /> :
        <ul className="divide-y divide-line">
            {shown.map((n) =>
          <li key={n.id}>
                <button onClick={() => open(n)} className="flex w-full items-start gap-3 px-5 py-4 text-left transition-colors duration-150 hover:bg-canvas">
                  <span className={cn('mt-1.5 h-2 w-2 shrink-0 rounded-full', n.read ? 'bg-line' : dot[n.tone])} aria-hidden />
                  <span className="min-w-0 flex-1">
                    <span className={cn('block text-sm', n.read ? 'font-medium text-ink-2' : 'font-semibold text-ink')}>{n.title}{!n.read && <span className="sr-only"> (unread)</span>}</span>
                    <span className="mt-0.5 block text-sm text-ink-muted">{n.body}</span>
                  </span>
                  <time className="shrink-0 text-xs text-ink-faint" dateTime={n.createdAt}>{fmtDateTime(n.createdAt)}</time>
                </button>
              </li>
          )}
          </ul>
        }
      </Panel>
    </div>);

}