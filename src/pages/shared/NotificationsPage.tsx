import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { BellIcon, CheckCheckIcon, Trash2Icon, ArchiveIcon } from 'lucide-react';
import { Button } from '../../components/ui/Button';
import { EmptyState, PageHeader, Panel, Segmented } from '../../components/ui/Primitives';
import { useAuth } from '../../contexts/AuthContext';
import { useData } from '../../contexts/DataContext';
import type { AppNotification, Tone } from '@shared/types';
import { cn } from '../../utils/cn';
import { cmd } from '../../utils/commands';
import { fmtDateTime } from '@shared/domain/time';
import { ConfirmDialog } from '../../components/ui/ConfirmDialog';

const dot: Record<Tone, string> = { ok: 'bg-ok', warn: 'bg-warn', bad: 'bg-bad', info: 'bg-info', brand: 'bg-brand-600', neutral: 'bg-ink-faint' };

export function NotificationsPage() {
  const { user } = useAuth();
  const { state, run } = useData();
  const navigate = useNavigate();
  const [filter, setFilter] = useState<'all' | 'unread' | 'archived'>('all');
  const audience = user?.role === 'management' ? 'management' : user?.employeeId ?? '';
  const mine = state.notifications.filter((n) => n.audience === audience && !n.archived);
  const archived = state.notifications.filter((n) => n.audience === audience && n.archived);
  const shown = filter === 'unread' ? mine.filter((n) => !n.read) : filter === 'archived' ? archived : mine;
  const unread = mine.filter((n) => !n.read).length;

  const markRead = (ids: string[]) => run(cmd.markNotificationsRead(ids));
  const deleteNotifications = (ids: string[]) => run(cmd.deleteNotifications(ids));
  const archiveNotifications = (ids: string[]) => run(cmd.archiveNotifications(ids));

  const open = (n: AppNotification) => {
    if (!n.read) markRead([n.id]);
    navigate(n.link);
  };

  const [deleteOpen, setDeleteOpen] = useState(false);
  const [archiveOpen, setArchiveOpen] = useState(false);
  const [deleteIds, setDeleteIds] = useState<string[]>([]);
  const [archiveIds, setArchiveIds] = useState<string[]>([]);

  const confirmDelete = (ids: string[]) => {
    setDeleteIds(ids);
    setDeleteOpen(true);
  };
  const confirmArchive = (ids: string[]) => {
    setArchiveIds(ids);
    setArchiveOpen(true);
  };

  const emptyTitle = filter === 'unread'
    ? 'No unread notifications'
    : filter === 'archived'
      ? 'No archived notifications'
      : 'No notifications yet';

  const headerActions = (
    <>
      <Button variant="secondary" icon={CheckCheckIcon} disabled={!unread} onClick={() => markRead(mine.map((n) => n.id))}>
        Mark all as read
      </Button>
      {archived.length > 0 && (
        <Button variant="danger" icon={Trash2Icon} disabled={deleteOpen} onClick={() => confirmDelete(archived.map((n) => n.id))}>
          Delete all archived
        </Button>
      )}
    </>
  );

  return (
    <div>
      <PageHeader
        title="Notifications"
        description="Notifications are generated by the system and stored with your records."
        actions={headerActions}
      />
      <div className="mb-4">
        <Segmented
          label="Filter"
          value={filter}
          onChange={setFilter}
          options={[
            { value: 'all', label: `All (${mine.length})` },
            { value: 'unread', label: `Unread (${unread})` },
            { value: 'archived', label: `Archived (${archived.length})` }
          ]}
        />
      </div>
      <Panel flush>
        {shown.length === 0 ? (
          <EmptyState icon={BellIcon} title={emptyTitle} />
        ) : (
          <ul className="divide-y divide-line">
            {shown.map((n) => (
              <li key={n.id}>
                <button
                  type="button"
                  onClick={() => open(n)}
                  className="flex w-full items-start gap-3 px-5 py-4 text-left transition-colors duration-150 hover:bg-canvas"
                >
                  <span className={cn('mt-1.5 h-2 w-2 shrink-0 rounded-full', n.read ? 'bg-line' : dot[n.tone])} aria-hidden />
                  <span className="min-w-0 flex-1">
                    <div className="flex items-start justify-between gap-2">
                      <span className={cn('block text-sm', n.read ? 'font-medium text-ink-2' : 'font-semibold text-ink')}>
                        {n.title}{!n.read && <span className="sr-only"> (unread)</span>}
                      </span>
                      <div className="flex items-center gap-2">
                        <button
                          type="button"
                          onClick={(e) => {
                            e.stopPropagation();
                            confirmArchive([n.id]);
                          }}
                          className="h-6 w-6 rounded-md border border-line-strong text-xs text-ink-muted hover:bg-canvas transition-colors"
                          title="Archive"
                        >
                          <ArchiveIcon className="h-3 w-3" />
                        </button>
                        <button
                          type="button"
                          onClick={(e) => {
                            e.stopPropagation();
                            confirmDelete([n.id]);
                          }}
                          className="h-6 w-6 rounded-md border border-line-strong text-xs text-ink-muted hover:bg-canvas transition-colors"
                          title="Delete"
                        >
                          <Trash2Icon className="h-3 w-3" />
                        </button>
                      </div>
                    </div>
                    <span className="mt-0.5 block text-sm text-ink-muted">{n.body}</span>
                  </span>
                  <time className="shrink-0 text-xs text-ink-faint" dateTime={n.createdAt}>{fmtDateTime(n.createdAt)}</time>
                </button>
              </li>
            ))}
          </ul>
        )}
      </Panel>

      <ConfirmDialog
        open={deleteOpen}
        onClose={() => setDeleteOpen(false)}
        title={`Delete ${deleteIds.length} notification${deleteIds.length > 1 ? 's' : ''}?`}
        body="Deleted notifications cannot be recovered."
        confirmLabel="Delete"
        tone="danger"
        onConfirm={() => {
          deleteNotifications(deleteIds);
          setDeleteOpen(false);
        }}
      />

      <ConfirmDialog
        open={archiveOpen}
        onClose={() => setArchiveOpen(false)}
        title={`Archive ${archiveIds.length} notification${archiveIds.length > 1 ? 's' : ''}?`}
        body="Archived notifications are moved out of your main view but can still be seen in the Archived filter."
        confirmLabel="Archive"
        onConfirm={() => {
          archiveNotifications(archiveIds);
          setArchiveOpen(false);
        }}
      />
    </div>
  );
}